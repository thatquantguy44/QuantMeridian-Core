import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("five-dataset pipeline bundle is selected explicitly and keeps fixture labels", async ({ page }) => {
  test.skip(process.env.PRES_BUNDLE_E2E !== "1", "Requires an explicitly configured fictional pipeline bundle.");
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/presidential-impact");
  await expect(page.getByText("No research dataset loaded", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Check for pipeline snapshots" }).click();
  await expect(page.getByLabel("Pipeline dataset").locator("option")).toHaveCount(5);
  await page.getByLabel("Pipeline dataset").selectOption("shiller-sp-composite-annual");
  await page.getByRole("button", { name: "Load pipeline snapshot" }).click();
  await expect(page.getByLabel("Pipeline snapshot provenance")).toContainText("fixture-complete");
  await expect(page.getByLabel("Pipeline snapshot provenance")).toContainText("SHILLER_001 first seen");
  await expect(page.locator("p").filter({ hasText: "Fictional fixture — Shiller S&P Composite" }).first()).toBeVisible();
  await expect(page.getByText(/Full sample:/)).toContainText("2");
  const ledger = page.getByRole("table", { name: "Matched annual comparison ledger" });
  await expect(ledger.locator("tbody tr")).toHaveCount(2);
  await expect(page.getByText(/Full paired sample: 2 included/)).toBeVisible();
  await page.getByLabel("Your interpretation").fill("Offline fixture interpretation.");
  await page.getByLabel("Additional sensitivity years (comma-separated)").fill("1936");
  await expect(page.getByText(/Sensitivity excluding 1936: 1 included/)).toBeVisible();
  await expect(ledger.locator("tbody tr").first()).toContainText("Excluded");
  await page.getByLabel("Comparison sample").selectOption("inherited");
  await expect(ledger.locator("tbody tr").first()).toContainText("observed 1935-10-31");
  await expect(ledger.locator("tbody tr").first()).toContainText("assumed available 1935-11-01");
  await expect(page.getByText(/not verified real-time vintages/).first()).toBeVisible();
  const pairedCsvWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download paired CSV" }).click();
  expect(await readFile((await (await pairedCsvWait).path())!, "utf8")).toContain("SYNTHETIC_FIXTURE");
  const pairedReplayWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download paired replay" }).click();
  const pairedReplay = await readFile((await (await pairedReplayWait).path())!);
  expect(JSON.parse(pairedReplay.toString()).schemaVersion).toBe("presidential-run/2");
  const pairedSvgWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Matched CRSP proxy groups SVG" }).click();
  expect(await readFile((await (await pairedSvgWait).path())!, "utf8")).toContain("DEMO · ILLUSTRATIVE DATA");
  const pairedPngWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Matched Shiller groups PNG" }).click();
  expect((await readFile((await (await pairedPngWait).path())!)).subarray(1, 4).toString()).toBe("PNG");
  const cycle = page.getByRole("table", { name: "Presidential cycle annual ledger" });
  await expect(cycle.locator("tbody tr")).toHaveCount(1);
  await expect(page.getByText(/Pre-1937 excluded: 1936/)).toBeVisible();
  await page.getByLabel("Highlight inauguration transitions").focus();
  await page.keyboard.press("Space");
  await expect(page.getByLabel("Highlight inauguration transitions")).toBeChecked();
  await expect(cycle.locator("tbody tr")).toHaveCount(1);
  await expect(cycle).toContainText("Inauguration transition highlighted");
  await page.getByLabel("Cycle return construction").selectOption("shiller");
  await expect(page.getByLabel("Cycle return construction")).toHaveValue("shiller");
  await expect(page.getByRole("table", { name: "Presidential cycle group summary" })).toContainText("Unavailable");
  const cycleCsvWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download cycle CSV" }).click();
  expect(await readFile((await (await cycleCsvWait).path())!, "utf8")).toContain("SYNTHETIC_FIXTURE");
  const cycleReplayWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download cycle replay" }).click();
  const cycleReplay = await readFile((await (await cycleReplayWait).path())!);
  const cycleSvgWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Presidential cycle summary SVG" }).click();
  expect(await readFile((await (await cycleSvgWait).path())!, "utf8")).toContain("DEMO · ILLUSTRATIVE DATA");
  const cyclePngWait = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download Presidential cycle summary PNG" }).click();
  expect((await readFile((await (await cyclePngWait).path())!)).subarray(1, 4).toString()).toBe("PNG");
  await page.getByLabel("Pipeline dataset").selectOption("crsp-market-proxy-annual");
  await page.getByRole("button", { name: "Load pipeline snapshot" }).click();
  await expect(page.locator("p").filter({ hasText: "Fictional fixture — Public CRSP-market-proxy" }).first()).toBeVisible();
  await expect(page.getByText(/Full sample:/)).toContainText("3");
  await expect(page.getByText("DEMO · ILLUSTRATIVE DATA", { exact: true })).toBeVisible();
  const blocked: string[] = [];
  await page.route("**/api/presidential/research/**", route => { blocked.push(route.request().url()); return route.abort(); });
  await page.getByRole("button", { name: "Clear dataset", exact: true }).click();
  await page.getByLabel("Import saved research run").setInputFiles({ name: "paired.json", mimeType: "application/json", buffer: pairedReplay });
  await expect(page.getByLabel("Comparison sample")).toHaveValue("inherited");
  await expect(page.getByLabel("Additional sensitivity years (comma-separated)")).toHaveValue("1936");
  await expect(page.getByLabel("Your interpretation")).toHaveValue("Offline fixture interpretation.");
  await expect(page.getByText(/Sensitivity excluding 1936: 1 included/)).toBeVisible();
  await page.getByLabel("Import saved research run").setInputFiles({ name: "cycle.json", mimeType: "application/json", buffer: cycleReplay });
  await expect(page.getByLabel("Cycle return construction")).toHaveValue("shiller");
  await expect(page.getByLabel("Highlight inauguration transitions")).toBeChecked();
  await expect(page.getByLabel("Your interpretation")).toHaveValue("Offline fixture interpretation.");
  const corrupt = JSON.parse(cycleReplay.toString()); corrupt.provenanceSha256 = "0".repeat(64);
  await page.getByLabel("Import saved research run").setInputFiles({ name: "corrupt.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(corrupt)) });
  await expect(page.getByRole("alert")).toContainText("does not reconcile");
  await expect(page.getByLabel("Cycle return construction")).toHaveValue("shiller");
  await expect(page.getByLabel("Your interpretation")).toHaveValue("Offline fixture interpretation.");
  expect(blocked).toEqual([]);
  await page.setViewportSize({ width: 320, height: 1000 });
  expect(await page.locator("main").evaluate(element => element.scrollWidth > element.clientWidth + 1)).toBe(false);
  expect(errors).toEqual([]);
});
